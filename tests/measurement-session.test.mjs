import test from 'node:test';
import assert from 'node:assert/strict';
import session from '../api/measurement-session.js';

function response() {
  return { statusCode: 0, headers: {}, setHeader(k, v) { this.headers[k] = v; }, end(value) { this.body = JSON.parse(value); } };
}

async function withEnv(fn) {
  const keys = ['MEASUREMENT_OWNER_EMAIL', 'SUPABASE_URL', 'SUPABASE_SECRET_KEY', 'RESEND_API_KEY', 'ORKESTA_EMAIL_FROM'];
  const original = Object.fromEntries(keys.map(key => [key, process.env[key]]));
  const originalFetch = global.fetch;
  Object.assign(process.env, {
    MEASUREMENT_OWNER_EMAIL: 'owner@example.com', SUPABASE_URL: 'https://db.example.test',
    SUPABASE_SECRET_KEY: 'server-secret', RESEND_API_KEY: 'mail-secret',
    ORKESTA_EMAIL_FROM: 'Orkesta <info@example.com>',
  });
  try { await fn(); } finally {
    global.fetch = originalFetch;
    for (const key of keys) if (original[key] === undefined) delete process.env[key]; else process.env[key] = original[key];
  }
}

test('access code can be requested only for the configured owner email', async () => withEnv(async () => {
  let calls = 0;
  global.fetch = async () => { calls++; throw new Error('unexpected fetch'); };
  const res = response();
  await session({ method: 'POST', body: { email: 'stranger@example.com' }, headers: {} }, res);
  assert.equal(res.statusCode, 403);
  assert.equal(calls, 0);
}));

test('access code is generated by Supabase and mailed only to the owner', async () => withEnv(async () => {
  const calls = [];
  global.fetch = async (url, options) => {
    calls.push({ url: String(url), options });
    if (String(url).includes('/admin/generate_link')) return new Response(JSON.stringify({ email_otp: '123456', verification_type: 'magiclink' }), { status: 200 });
    return new Response('{}', { status: 200 });
  };
  const res = response();
  await session({ method: 'POST', body: { email: 'owner@example.com' }, headers: {} }, res);
  assert.equal(res.statusCode, 200);
  assert.equal(calls[0].url, 'https://db.example.test/auth/v1/admin/generate_link');
  assert.deepEqual(JSON.parse(calls[0].options.body), { type: 'magiclink', email: 'owner@example.com' });
  assert.equal(calls[1].url, 'https://api.resend.com/emails');
  assert.deepEqual(JSON.parse(calls[1].options.body).to, ['owner@example.com']);
  assert.match(JSON.parse(calls[1].options.body).text, /123456/);
}));

test('valid emailed code creates an owner-only session', async () => withEnv(async () => {
  const calls = [];
  global.fetch = async (url, options) => {
    calls.push({ url: String(url), options });
    if (String(url).endsWith('/verify')) return new Response(JSON.stringify({ access_token: 'owner-token', expires_in: 3600 }), { status: 200 });
    return new Response(JSON.stringify({ email: 'owner@example.com', email_confirmed_at: '2026-11-15T00:00:00Z' }), { status: 200 });
  };
  const res = response();
  await session({ method: 'PUT', body: { email: 'owner@example.com', code: '123456' }, headers: {} }, res);
  assert.equal(res.statusCode, 200);
  assert.deepEqual(JSON.parse(calls[0].options.body), { type: 'magiclink', email: 'owner@example.com', token: '123456' });
  assert.match(res.headers['Set-Cookie'], /HttpOnly; Secure; SameSite=Strict/);
}));
