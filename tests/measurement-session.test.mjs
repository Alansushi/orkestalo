test('valid emailed code creates an owner-only session', async () => withEnv(async () => {
  const calls = [];
  global.fetch = async (url, options) => {
    calls.push({ url: String(url), options });
    if (String(url).endsWith('/verify')) return new Response(JSON.stringify({ access_token: 'owner-token', expires_in: 3600 }), { status: 200 });
    return new Response(JSON.stringify({ email: 'owner@example.com', email_confirmed_at: '2026-11-15T00:00:00Z' }), { status: 200 });
  };
  const res = response();
  await session({ method: 'PUT', body: { email: 'owner@example.com', code: '123456', type: 'signup' }, headers: {} }, res);
  assert.equal(res.statusCode, 200);
  assert.equal(res.body.mfa, 'enroll');
  assert.doesNotMatch(res.headers['Set-Cookie'], /orkesta_measurement_session=/);
  assert.deepEqual(JSON.parse(calls[0].options.body), { type: 'signup', email: 'owner@example.com', token: '123456' });
  assert.match(res.headers['Set-Cookie'], /orkesta_measurement_pending=/);
}));

